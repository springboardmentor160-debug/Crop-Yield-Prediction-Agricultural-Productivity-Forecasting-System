"""
YieldSense AI  -  Reports API Endpoints
"""

from fastapi import APIRouter, Depends, HTTPException

from app.api.deps import get_current_user_id
from app.schemas.report import ReportRequest, ReportResponse, ReportListResponse, ReportSummary
from app.schemas.auth import MessageResponse
from app.services.report_service import ReportService
from app.utils.exceptions import NotFoundException, ForbiddenException

router = APIRouter(prefix="/reports", tags=["Reports"])


@router.post("/", response_model=ReportResponse, status_code=201, summary="Generate a report")
async def generate_report(
    request: ReportRequest,
    user_id: str = Depends(get_current_user_id),
):
    """
    Generate a professional report from a prediction record.
    Assembles prediction data, risk assessment, and recommendations,
    then saves the full report to Firestore.
    """
    try:
        svc = ReportService()
        result = svc.generate_report(
            user_id=user_id,
            prediction_id=request.prediction_id,
            report_type=request.report_type,
            title=request.title,
            farm_id=request.farm_id,
        )
        return ReportResponse(**result)
    except NotFoundException as e:
        raise HTTPException(status_code=404, detail=str(e))
    except ForbiddenException as e:
        raise HTTPException(status_code=403, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Report generation failed: {str(e)}")


@router.get("/", response_model=ReportListResponse, summary="List user reports")
async def list_reports(user_id: str = Depends(get_current_user_id)):
    """Get all reports generated by the authenticated user."""
    try:
        svc = ReportService()
        reports = svc.get_reports(user_id)
        return ReportListResponse(reports=reports, total=len(reports))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Error fetching reports: {str(e)}")


@router.get("/{report_id}", response_model=ReportResponse, summary="Get report details")
async def get_report(
    report_id: str,
    user_id: str = Depends(get_current_user_id),
):
    """Get a single report with full data payload."""
    try:
        svc = ReportService()
        report = svc.get_report(report_id, user_id)
        return ReportResponse(**report)
    except NotFoundException as e:
        raise HTTPException(status_code=404, detail=str(e))
    except ForbiddenException as e:
        raise HTTPException(status_code=403, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Error fetching report: {str(e)}")


@router.delete("/{report_id}", response_model=MessageResponse, summary="Delete a report")
async def delete_report(
    report_id: str,
    user_id: str = Depends(get_current_user_id),
):
    """Delete a report (with ownership check)."""
    try:
        svc = ReportService()
        result = svc.delete_report(report_id, user_id)
        return MessageResponse(message=result["message"], success=True)
    except NotFoundException as e:
        raise HTTPException(status_code=404, detail=str(e))
    except ForbiddenException as e:
        raise HTTPException(status_code=403, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Error deleting report: {str(e)}")
